#!/usr/bin/env python3
"""Generate a context-free, positional-arg shim over sqlc's Queries (v3).

- Strips ctx (context.Background injected).
- Methods sqlc wrapped in a single XxxParams struct are expanded to positional
  parameters for ergonomic call sites.
- gen-package types qualified with the gen. prefix.
"""
import re, os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
GEN = os.path.join(ROOT, "internal/repo/gen")
OUT = os.path.join(ROOT, "internal/repo/shim.go")

BUILTIN = {
    "string", "int64", "int32", "int", "float64", "float32", "bool", "byte",
    "[]byte", "[]string", "error", "interface{}", "any", "time.Time", "context.Context",
}

sig_re = re.compile(r"^func \(q \*Queries\) (\w+)\(([^)]*)\)\s+(.+?) \{$", re.M)
params_struct_re = re.compile(r"^type (\w+Params) struct \{\n(.*?)^\}", re.M | re.S)

def qual_type(t: str) -> str:
    t = t.strip()
    m = re.match(r"^(\[\])?(\*?)(.+)$", t)
    pre, star, base = m.group(1) or "", m.group(2) or "", m.group(3)
    if base in BUILTIN or base.startswith("sql.") or base.startswith("time."):
        return t
    return f"{pre}{star}gen.{base}"

def parse_params(sig: str):
    """returns list of (name, type) after qualification; expands single XxxParams arg."""
    sig = sig.strip()
    if not sig:
        return []
    out = []
    for tok in [p.strip() for p in sig.split(",")]:
        m = re.match(r"^(\w+)\s+(.+)$", tok)
        if not m:
            return None  # weird; signal skip
        out.append((m.group(1), m.group(2).strip()))
    return out

def struct_fields(src: str, sname: str):
    m = params_struct_re.search(src)
    while m:
        if m.group(1) == sname:
            fields = []
            for line in m.group(2).strip().splitlines():
                line = line.strip()
                if not line or line.startswith("//"):
                    continue
                fm = re.match(r"^(\w+)\s+(\S+)$", line)
                if fm:
                    fields.append((fm.group(1), fm.group(2)))
            return fields
        m = params_struct_re.search(src, m.end())
    return None

methods = {}  # name -> (params list of (name,type), ret string, expanded struct or None)
for fname in sorted(os.listdir(GEN)):
    if not fname.endswith(".sql.go"):
        continue
    src = open(os.path.join(GEN, fname)).read()
    for m in sig_re.finditer(src):
        name, psig, rsig = m.group(1), m.group(2), m.group(3)
        psig = re.sub(r"^ctx context\.Context(?:,\s*)?", "", psig)
        params = parse_params(psig)
        if params is None:
            continue
        # expand single struct param
        sname = None
        if len(params) == 1 and params[0][1].endswith("Params"):
            sname = params[0][1]
            fields = struct_fields(src, sname)
            if fields is None:
                continue
            params = fields
        # qualify return
        ret = rsig.strip()
        if ret.startswith("(") and ret.endswith(")"):
            inner = ret[1:-1]
            ret_parts = [qual_type(p) for p in inner.split(",")] if inner.strip() else []
            ret_q = "(" + ", ".join(ret_parts) + ")"
        else:
            ret_q = qual_type(ret)
        methods[name] = ([(n, qual_type(t)) for n, t in params], ret_q, sname)

lines = [
    "// Code generated by scripts/gen_shim.py; DO NOT EDIT MANUALLY.",
    "// Context-free wrappers around the sqlc-generated query methods.",
    "package repo",
    "",
    'import "context"',
    "",
    'import "github.com/FlameInTheDark/servy/internal/repo/gen"',
    "",
    "// Q wraps gen.Queries, hiding the ctx parameter (context.Background is used).",
    "type Q struct {",
    "\t*gen.Queries",
    "}",
    "",
    "// NewQ builds the ctx-free wrapper.",
    "func NewQ(inner *gen.Queries) Q { return Q{Queries: inner} }",
    "",
]
for name in sorted(methods):
    params, ret_q, sname = methods[name]
    psig = ", ".join(f"{n} {t}" for n, t in params)
    args = ", ".join(n for n, _ in params)
    if sname:
        fields = ", ".join(f"{n}: {n}" for n, _ in params)
        call = f"context.Background(), gen.{sname}{{{fields}}}"
    else:
        call = f"context.Background(){', ' + args if args else ''}"
    if ret_q and ret_q != "()":
        lines.append(f"func (q *Q) {name}({psig}) {ret_q} {{")
        lines.append(f"\treturn q.Queries.{name}({call})")
    else:
        lines.append(f"func (q *Q) {name}({psig}) {{")
        lines.append(f"\tq.Queries.{name}({call})")
    lines.append("}")
    lines.append("")

with open(OUT, "w") as f:
    f.write("\n".join(lines))
print(f"wrote {len(methods)} methods to {OUT}")
